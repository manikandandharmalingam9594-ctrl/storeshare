"""
StoreShare SQLite-to-PostgreSQL Data Migration Script
=====================================================
Safely migrates metadata, users, provider nodes, files, chunks, and chunk jobs
from SQLite (read-only) to PostgreSQL in foreign-key dependency order.

Guarantees:
- Never modifies the source SQLite database.
- Wraps entire migration in a PostgreSQL transaction for atomic commit/rollback.
- Converts SQLite booleans (0/1) to Python bools for PostgreSQL BOOLEAN columns.
- Preserves exact primary keys, timestamps, and relationships.
- Synchronizes PostgreSQL identity sequences (setval) to prevent sequence collisions.
- Validates pre-migration target state and post-migration row counts and field integrity.
"""

import argparse
from datetime import datetime, timezone
import hashlib
import json
import logging
import os
from pathlib import Path
import sqlite3
import sys
from typing import Any, Dict, List, Optional, Tuple

PROJECT_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(PROJECT_ROOT))

from dotenv import load_dotenv
load_dotenv(PROJECT_ROOT / ".env")

import psycopg
from psycopg.rows import dict_row

logging.basicConfig(
    level=logging.INFO,
    format="%(asctime)s [%(levelname)s] %(name)s: %(message)s"
)
logger = logging.getLogger("storeshare-migration")


def parse_timestamp(val: Any) -> Optional[datetime]:
    """Parse SQLite timestamp string or return datetime directly."""
    if val is None:
        return None
    if isinstance(val, datetime):
        return val
    val_str = str(val).strip()
    # Try ISO formats and standard SQLite format
    for fmt in ("%Y-%m-%d %H:%M:%S", "%Y-%m-%d %H:%M:%S.%f", "%Y-%m-%dT%H:%M:%S", "%Y-%m-%dT%H:%M:%S.%f"):
        try:
            return datetime.strptime(val_str, fmt).replace(tzinfo=timezone.utc)
        except ValueError:
            pass
    try:
        return datetime.fromisoformat(val_str)
    except Exception:
        return None


def get_sqlite_connection(sqlite_path: Path) -> sqlite3.Connection:
    """Open source SQLite database in read-only mode to prevent any modification."""
    conn = sqlite3.connect(f"file:{sqlite_path.resolve()}?mode=ro", uri=True)
    conn.row_factory = sqlite3.Row
    return conn


def check_target_conflicts(conn_pg: psycopg.Connection) -> Dict[str, int]:
    """Check target PostgreSQL tables and count existing rows."""
    tables = ["app_metadata", "users", "provider_nodes", "files", "file_chunks", "chunk_jobs"]
    counts = {}
    with conn_pg.cursor() as cur:
        for tbl in tables:
            try:
                cur.execute(f"SELECT COUNT(*) as count FROM {tbl}")
                counts[tbl] = cur.fetchone()["count"]
            except psycopg.errors.UndefinedTable:
                counts[tbl] = -1  # Table does not exist yet
    return counts


def create_postgres_schema(conn_pg: psycopg.Connection):
    """
    Ensure all six tables, constraints, identity columns, foreign keys, and indexes exist.
    """
    logger.info("Verifying / creating PostgreSQL schema tables and constraints...")
    with conn_pg.cursor() as cur:
        # 1. Foundation metadata table
        cur.execute("""
            CREATE TABLE IF NOT EXISTS app_metadata (
                key VARCHAR(128) PRIMARY KEY,
                value TEXT NOT NULL,
                created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
            );
        """)

        # 2. Users table
        cur.execute("""
            CREATE TABLE IF NOT EXISTS users (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                email VARCHAR(255) NOT NULL UNIQUE,
                password_hash VARCHAR(255) NOT NULL,
                role VARCHAR(32) NOT NULL DEFAULT 'CONSUMER' CHECK (role IN ('CONSUMER', 'PROVIDER', 'ADMIN')),
                is_active BOOLEAN NOT NULL DEFAULT TRUE,
                created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
            );
            CREATE INDEX IF NOT EXISTS idx_users_email ON users(email);
        """)

        # 3. Provider nodes table
        cur.execute("""
            CREATE TABLE IF NOT EXISTS provider_nodes (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                provider_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
                storage_dir VARCHAR(1024) NOT NULL,
                quota_bytes BIGINT NOT NULL DEFAULT 0,
                used_bytes BIGINT NOT NULL DEFAULT 0,
                reserved_bytes BIGINT NOT NULL DEFAULT 0,
                status VARCHAR(32) NOT NULL DEFAULT 'OFFLINE' CHECK (status IN ('ONLINE', 'OFFLINE', 'STOPPED')),
                last_heartbeat TIMESTAMPTZ,
                created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
                updated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
            );
            CREATE INDEX IF NOT EXISTS idx_provider_nodes_provider_id ON provider_nodes(provider_id);
            CREATE INDEX IF NOT EXISTS idx_provider_nodes_status ON provider_nodes(status);
        """)

        # 4. Files table
        cur.execute("""
            CREATE TABLE IF NOT EXISTS files (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                owner_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
                filename VARCHAR(255) NOT NULL,
                file_size BIGINT NOT NULL,
                encrypted_size BIGINT NOT NULL,
                iv_hex VARCHAR(64) NOT NULL,
                sha256_hash VARCHAR(64) NOT NULL,
                status VARCHAR(32) NOT NULL DEFAULT 'PENDING_UPLOAD' CHECK (status IN ('PENDING_UPLOAD', 'STORED', 'DELETED', 'FAILED')),
                created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
                updated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
            );
            CREATE INDEX IF NOT EXISTS idx_files_owner_id ON files(owner_id);
            CREATE INDEX IF NOT EXISTS idx_files_status ON files(status);
        """)

        # 5. File chunks table
        cur.execute("""
            CREATE TABLE IF NOT EXISTS file_chunks (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                file_id BIGINT NOT NULL REFERENCES files(id) ON DELETE CASCADE,
                chunk_id VARCHAR(128) NOT NULL UNIQUE,
                provider_node_id BIGINT NOT NULL REFERENCES provider_nodes(id) ON DELETE CASCADE,
                chunk_index INTEGER NOT NULL DEFAULT 0,
                chunk_size BIGINT NOT NULL,
                status VARCHAR(32) NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING', 'STORED', 'FAILED')),
                created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
            );
            CREATE INDEX IF NOT EXISTS idx_file_chunks_file_id ON file_chunks(file_id);
            CREATE INDEX IF NOT EXISTS idx_file_chunks_provider_node_id ON file_chunks(provider_node_id);
            CREATE INDEX IF NOT EXISTS idx_file_chunks_chunk_id ON file_chunks(chunk_id);
        """)

        # 6. Chunk transfer jobs table
        cur.execute("""
            CREATE TABLE IF NOT EXISTS chunk_jobs (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                provider_node_id BIGINT NOT NULL REFERENCES provider_nodes(id) ON DELETE RESTRICT,
                chunk_id VARCHAR(128) NOT NULL,
                file_id BIGINT NOT NULL REFERENCES files(id) ON DELETE CASCADE,
                job_type VARCHAR(32) NOT NULL CHECK (job_type IN ('STORE_CHUNK', 'RETRIEVE_CHUNK', 'DELETE_CHUNK')),
                status VARCHAR(32) NOT NULL DEFAULT 'QUEUED' CHECK (status IN ('QUEUED', 'PROCESSING', 'COMPLETED', 'FAILED', 'TIMED_OUT')),
                expires_at TIMESTAMPTZ NOT NULL,
                error_message TEXT,
                created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
                updated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
            );
            CREATE INDEX IF NOT EXISTS idx_chunk_jobs_provider_node_id ON chunk_jobs(provider_node_id);
            CREATE INDEX IF NOT EXISTS idx_chunk_jobs_status ON chunk_jobs(status);
            CREATE INDEX IF NOT EXISTS idx_chunk_jobs_chunk_id ON chunk_jobs(chunk_id);
        """)
    logger.info("PostgreSQL schema tables verified.")


def migrate_data(
    sqlite_path: Path,
    pg_url: str,
    truncate_target: bool = False,
    dry_run: bool = False
) -> Dict[str, Any]:
    """
    Perform full data migration from SQLite to PostgreSQL.
    """
    logger.info(f"Opening read-only SQLite source: {sqlite_path}")
    conn_sqlite = get_sqlite_connection(sqlite_path)

    logger.info("Connecting to target PostgreSQL...")
    conn_pg = psycopg.connect(pg_url, row_factory=dict_row)

    report: Dict[str, Any] = {
        "source_counts": {},
        "target_counts_before": {},
        "migrated_counts": {},
        "target_counts_after": {},
        "dry_run": dry_run,
        "status": "IN_PROGRESS",
    }

    try:
        # Check initial target counts
        target_before = check_target_conflicts(conn_pg)
        report["target_counts_before"] = target_before

        # Reset connection to clean IDLE state after conflict query
        conn_pg.rollback()

        has_existing = any(cnt > 0 for cnt in target_before.values())
        if has_existing and not truncate_target:
            raise RuntimeError(
                f"Target PostgreSQL tables already contain data: {target_before}. "
                "Specify truncate_target=True or resolve conflicts before migrating."
            )

        with conn_pg.transaction():
            create_postgres_schema(conn_pg)

            if truncate_target and has_existing:
                logger.warning("Truncating target PostgreSQL tables prior to clean migration...")
                with conn_pg.cursor() as cur:
                    cur.execute("""
                        TRUNCATE TABLE chunk_jobs, file_chunks, files, provider_nodes, users, app_metadata
                        RESTART IDENTITY CASCADE;
                    """)
                logger.info("Target tables truncated.")

            # 1. Migrate app_metadata
            logger.info("Migrating app_metadata...")
            cur_sqlite = conn_sqlite.cursor()
            cur_sqlite.execute("SELECT key, value, created_at FROM app_metadata ORDER BY key")
            meta_rows = [dict(r) for r in cur_sqlite.fetchall()]
            report["source_counts"]["app_metadata"] = len(meta_rows)

            with conn_pg.cursor() as cur_pg:
                for row in meta_rows:
                    cur_pg.execute("""
                        INSERT INTO app_metadata (key, value, created_at)
                        VALUES (%s, %s, %s)
                        ON CONFLICT (key) DO UPDATE SET value = EXCLUDED.value;
                    """, (row["key"], row["value"], parse_timestamp(row["created_at"])))
            report["migrated_counts"]["app_metadata"] = len(meta_rows)

            # 2. Migrate users
            logger.info("Migrating users...")
            cur_sqlite.execute("SELECT id, email, password_hash, role, is_active, created_at FROM users ORDER BY id")
            user_rows = [dict(r) for r in cur_sqlite.fetchall()]
            report["source_counts"]["users"] = len(user_rows)

            with conn_pg.cursor() as cur_pg:
                for row in user_rows:
                    is_active_bool = bool(row["is_active"])
                    cur_pg.execute("""
                        INSERT INTO users (id, email, password_hash, role, is_active, created_at)
                        VALUES (%s, %s, %s, %s, %s, %s);
                    """, (
                        row["id"],
                        row["email"],
                        row["password_hash"],
                        row["role"],
                        is_active_bool,
                        parse_timestamp(row["created_at"]),
                    ))
            report["migrated_counts"]["users"] = len(user_rows)

            # 3. Migrate provider_nodes
            logger.info("Migrating provider_nodes...")
            cur_sqlite.execute("""
                SELECT id, provider_id, storage_dir, quota_bytes, used_bytes, reserved_bytes,
                       status, last_heartbeat, created_at, updated_at
                FROM provider_nodes
                ORDER BY id
            """)
            node_rows = [dict(r) for r in cur_sqlite.fetchall()]
            report["source_counts"]["provider_nodes"] = len(node_rows)

            with conn_pg.cursor() as cur_pg:
                for row in node_rows:
                    cur_pg.execute("""
                        INSERT INTO provider_nodes (
                            id, provider_id, storage_dir, quota_bytes, used_bytes,
                            reserved_bytes, status, last_heartbeat, created_at, updated_at
                        )
                        VALUES (%s, %s, %s, %s, %s, %s, %s, %s, %s, %s);
                    """, (
                        row["id"],
                        row["provider_id"],
                        row["storage_dir"],
                        row["quota_bytes"],
                        row["used_bytes"],
                        row["reserved_bytes"],
                        row["status"],
                        parse_timestamp(row["last_heartbeat"]),
                        parse_timestamp(row["created_at"]),
                        parse_timestamp(row["updated_at"]),
                    ))
            report["migrated_counts"]["provider_nodes"] = len(node_rows)

            # 4. Migrate files
            logger.info("Migrating files...")
            cur_sqlite.execute("""
                SELECT id, owner_id, filename, file_size, encrypted_size, iv_hex, sha256_hash,
                       status, created_at, updated_at
                FROM files
                ORDER BY id
            """)
            file_rows = [dict(r) for r in cur_sqlite.fetchall()]
            report["source_counts"]["files"] = len(file_rows)

            with conn_pg.cursor() as cur_pg:
                for row in file_rows:
                    cur_pg.execute("""
                        INSERT INTO files (
                            id, owner_id, filename, file_size, encrypted_size, iv_hex,
                            sha256_hash, status, created_at, updated_at
                        )
                        VALUES (%s, %s, %s, %s, %s, %s, %s, %s, %s, %s);
                    """, (
                        row["id"],
                        row["owner_id"],
                        row["filename"],
                        row["file_size"],
                        row["encrypted_size"],
                        row["iv_hex"],
                        row["sha256_hash"],
                        row["status"],
                        parse_timestamp(row["created_at"]),
                        parse_timestamp(row["updated_at"]),
                    ))
            report["migrated_counts"]["files"] = len(file_rows)

            # 5. Migrate file_chunks
            logger.info("Migrating file_chunks...")
            cur_sqlite.execute("""
                SELECT id, file_id, chunk_id, provider_node_id, chunk_index, chunk_size,
                       status, created_at
                FROM file_chunks
                ORDER BY id
            """)
            chunk_rows = [dict(r) for r in cur_sqlite.fetchall()]
            report["source_counts"]["file_chunks"] = len(chunk_rows)

            with conn_pg.cursor() as cur_pg:
                for row in chunk_rows:
                    cur_pg.execute("""
                        INSERT INTO file_chunks (
                            id, file_id, chunk_id, provider_node_id, chunk_index,
                            chunk_size, status, created_at
                        )
                        VALUES (%s, %s, %s, %s, %s, %s, %s, %s);
                    """, (
                        row["id"],
                        row["file_id"],
                        row["chunk_id"],
                        row["provider_node_id"],
                        row["chunk_index"],
                        row["chunk_size"],
                        row["status"],
                        parse_timestamp(row["created_at"]),
                    ))
            report["migrated_counts"]["file_chunks"] = len(chunk_rows)

            # 6. Migrate chunk_jobs
            logger.info("Migrating chunk_jobs...")
            cur_sqlite.execute("""
                SELECT id, provider_node_id, chunk_id, file_id, job_type, status,
                       expires_at, error_message, created_at, updated_at
                FROM chunk_jobs
                ORDER BY id
            """)
            job_rows = [dict(r) for r in cur_sqlite.fetchall()]
            report["source_counts"]["chunk_jobs"] = len(job_rows)

            with conn_pg.cursor() as cur_pg:
                for row in job_rows:
                    cur_pg.execute("""
                        INSERT INTO chunk_jobs (
                            id, provider_node_id, chunk_id, file_id, job_type, status,
                            expires_at, error_message, created_at, updated_at
                        )
                        VALUES (%s, %s, %s, %s, %s, %s, %s, %s, %s, %s);
                    """, (
                        row["id"],
                        row["provider_node_id"],
                        row["chunk_id"],
                        row["file_id"],
                        row["job_type"],
                        row["status"],
                        parse_timestamp(row["expires_at"]),
                        row["error_message"],
                        parse_timestamp(row["created_at"]),
                        parse_timestamp(row["updated_at"]),
                    ))
            report["migrated_counts"]["chunk_jobs"] = len(job_rows)

            # 7. Synchronize identity sequences for tables with autoincrement IDs
            logger.info("Synchronizing PostgreSQL identity sequences...")
            with conn_pg.cursor() as cur_pg:
                cur_pg.execute("""
                    SELECT setval(pg_get_serial_sequence('users', 'id'), COALESCE(MAX(id), 1), MAX(id) IS NOT NULL) FROM users;
                    SELECT setval(pg_get_serial_sequence('provider_nodes', 'id'), COALESCE(MAX(id), 1), MAX(id) IS NOT NULL) FROM provider_nodes;
                    SELECT setval(pg_get_serial_sequence('files', 'id'), COALESCE(MAX(id), 1), MAX(id) IS NOT NULL) FROM files;
                    SELECT setval(pg_get_serial_sequence('file_chunks', 'id'), COALESCE(MAX(id), 1), MAX(id) IS NOT NULL) FROM file_chunks;
                    SELECT setval(pg_get_serial_sequence('chunk_jobs', 'id'), COALESCE(MAX(id), 1), MAX(id) IS NOT NULL) FROM chunk_jobs;
                """)
            logger.info("Identity sequences synchronized.")

            if dry_run:
                logger.info("DRY-RUN requested: Rolling back transaction cleanly...")
                raise KeyboardInterrupt("DRY_RUN_ROLLBACK")

        if not dry_run:
            conn_pg.commit()

        # After commit: verify counts
        report["target_counts_after"] = check_target_conflicts(conn_pg)
        report["status"] = "SUCCESS"
        logger.info("Migration transaction committed successfully.")

    except KeyboardInterrupt as ki:
        if str(ki) == "DRY_RUN_ROLLBACK":
            report["status"] = "DRY_RUN_SUCCESS"
            report["target_counts_after"] = check_target_conflicts(conn_pg)
            logger.info("Dry-run rollback completed successfully.")
        else:
            raise
    except Exception as exc:
        report["status"] = f"FAILED: {exc}"
        logger.error(f"Migration aborted and rolled back: {exc}", exc_info=True)
        raise
    finally:
        conn_sqlite.close()
        conn_pg.close()

    return report


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="StoreShare SQLite to PostgreSQL migration tool")
    parser.add_argument("--dry-run", action="store_true", help="Simulate migration and roll back")
    parser.add_argument("--truncate-target", action="store_true", help="Truncate target PG tables before migration")
    args = parser.parse_args()

    sqlite_db = PROJECT_ROOT / "data" / "storeshare.db"
    pg_conn_url = os.environ.get("STORESHARE_DATABASE_URL")
    if not pg_conn_url:
        print("Error: STORESHARE_DATABASE_URL not set in environment.")
        sys.exit(1)

    result = migrate_data(sqlite_db, pg_conn_url, truncate_target=args.truncate_target, dry_run=args.dry_run)
    print("\nMigration Execution Summary:")
    print(json.dumps(result, indent=2))
